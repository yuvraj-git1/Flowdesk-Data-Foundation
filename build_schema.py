"""Stage 1 build: validate schema, emit DDL + docs.

Outputs
-------
sql/01_schema.sql                 DuckDB DDL (+ COMMENTs) for public and _truth schemas
docs/data_dictionary.md           PUBLIC dictionary + ER diagram (no spoilers; safe to publish)
docs/data_dictionary.csv          same, machine-readable
_internal/planted_problem_map.md  PRIVATE: which columns each planted problem touches
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

from config import TARGETS
from schema import TABLES, PUBLIC, HIDDEN, ALL_PROBLEMS

ROOT = Path(__file__).parent
esc = lambda s: s.replace("'", "''")


# ------------------------------------------------------------------ validate
def validate():
    errs = []
    by_name = {t.name: t for t in TABLES}
    if len(by_name) != len(TABLES):
        errs.append("duplicate table names")
    if len(PUBLIC) != 17:
        errs.append(f"expected 17 public tables, found {len(PUBLIC)}")
    for t in TABLES:
        names = [c.name for c in t.cols]
        if len(set(names)) != len(names):
            errs.append(f"{t.name}: duplicate column names")
        pks = [c.name for c in t.cols if c.pk]
        if not pks and not t.composite_pk:
            errs.append(f"{t.name}: no primary key")
        for k in t.composite_pk:
            if k not in names:
                errs.append(f"{t.name}: composite pk col {k} missing")
        for c in t.cols:
            if c.fk:
                tt, cc = c.fk.split(".")
                if tt not in by_name or cc not in [x.name for x in by_name[tt].cols]:
                    errs.append(f"{t.name}.{c.name}: bad FK target {c.fk}")
    covered = {p.strip() for t in TABLES for c in t.cols for p in c.p.split(",") if p.strip()}
    missing = set(ALL_PROBLEMS) - covered
    if missing:
        errs.append(f"planted problems with no schema footprint: {sorted(missing)}")
    return errs


# ------------------------------------------------------------------ DDL
def ddl():
    out = ["-- Flowdesk schema (DuckDB). Generated by build_schema.py; do not edit by hand.",
           "-- No enforced FKs by design (bulk loads, planted orphans); see Stage 6 checks.",
           "CREATE SCHEMA IF NOT EXISTS _truth;", ""]
    for t in TABLES:
        lines = []
        for c in t.cols:
            lines.append(f"    {c.name} {c.dtype}" + (" NOT NULL" if c.not_null else ""))
        if t.composite_pk:
            lines.append(f"    PRIMARY KEY ({', '.join(t.composite_pk)})")
        else:
            lines[[c.pk for c in t.cols].index(True)] += " PRIMARY KEY"
        out.append(f"CREATE OR REPLACE TABLE {t.qname} (\n" + ",\n".join(lines) + "\n);")
        out.append(f"COMMENT ON TABLE {t.qname} IS '{esc(t.desc + ' Grain: ' + t.grain + '.')}';")
        for c in t.cols:
            out.append(f"COMMENT ON COLUMN {t.qname}.{c.name} IS '{esc(c.desc)}';")
        out.append("")
    return "\n".join(out)


# ------------------------------------------------------------------ public docs
def pub_md():
    o = ["# Flowdesk Data Dictionary", "",
         "Flowdesk is a product-led B2B SaaS team task app (Free / Pro / Business). "
         "Data covers **2023-01-01 to 2025-12-31**. All data is synthetic.", "",
         "## Conventions", "",
         "- Keys are integers. Foreign keys are **not enforced**; verify joins yourself.",
         "- Timestamps are UTC unless stated otherwise.",
         "- Money columns are in the row's `currency`; `*_usd` columns are USD equivalents.",
         "- Plans: Free (up to 5 users), Pro ($12/seat/mo list), Business ($24/seat/mo list). "
         "Annual billing is 20% cheaper than monthly.",
         "- This dictionary describes the *intended* contract of each column.", "",
         "## Tables", "",
         "| Table | Grain | Approx. rows |", "|---|---|---|"]
    for t in PUBLIC:
        o.append(f"| [{t.name}](#{t.name}) | {t.grain} | {t.rows} |")
    o += ["", "## Relationships", "", "```mermaid", "erDiagram"]
    for t in PUBLIC:
        for c in t.cols:
            if c.fk and c.fk.split(".")[0] in {p.name for p in PUBLIC}:
                parent = c.fk.split(".")[0]
                o.append(f'    {parent} ||--o{{ {t.name} : "{c.name}"')
    o += ["```", ""]
    for t in PUBLIC:
        o += [f"## {t.name}", "", t.desc, "", f"**Grain:** {t.grain}  ", f"**Approx. rows:** {t.rows}", "",
              "| Column | Type | Key | Null? | Description | Values / format |", "|---|---|---|---|---|---|"]
        for c in t.cols:
            key = "PK" if (c.pk or c.name in t.composite_pk) else (f"FK→{c.fk}" if c.fk else "")
            o.append(f"| `{c.name}` | {c.dtype} | {key} | {'no' if c.not_null else 'yes'} | "
                     f"{c.desc} | {(c.values or '').replace('|', '/')} |")
        o.append("")
    return "\n".join(o)


def pub_csv(path):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["table", "column", "type", "primary_key", "foreign_key", "nullable", "description", "values"])
        for t in PUBLIC:
            for c in t.cols:
                w.writerow([t.name, c.name, c.dtype, c.pk or c.name in t.composite_pk,
                            c.fk or "", not c.not_null, c.desc, c.values or ""])


# ------------------------------------------------------------------ internal map
def internal_md():
    m = defaultdict(list)
    for t in TABLES:
        for c in t.cols:
            for p in [x.strip() for x in c.p.split(",") if x.strip()]:
                m[p].append(f"`{t.qname}.{c.name}`")
    o = ["# PRIVATE: planted problem -> schema footprint", "",
         "Do not ship this file. It lists every column each problem touches.", "",
         "| Problem | Columns touched |", "|---|---|"]
    for p in ALL_PROBLEMS:
        o.append(f"| {p} | {', '.join(m[p])} |")
    return "\n".join(o)


# ------------------------------------------------------------------ main
if __name__ == "__main__":
    errs = validate()
    if errs:
        print("VALIDATION FAILED:\n - " + "\n - ".join(errs))
        sys.exit(1)

    (ROOT / "sql").mkdir(exist_ok=True); (ROOT / "docs").mkdir(exist_ok=True); (ROOT / "_internal").mkdir(exist_ok=True)
    (ROOT / "sql/01_schema.sql").write_text(ddl())
    (ROOT / "docs/data_dictionary.md").write_text(pub_md())
    pub_csv(ROOT / "docs/data_dictionary.csv")
    (ROOT / "_internal/planted_problem_map.md").write_text(internal_md())

    ncols = sum(len(t.cols) for t in PUBLIC)
    print(f"OK: {len(PUBLIC)} public tables ({ncols} columns), {len(HIDDEN)} _truth tables")
    print(f"    all {len(ALL_PROBLEMS)} planted problems have a schema footprint")

    try:
        import duckdb
        con = duckdb.connect()
        con.execute(ddl())
        n = con.execute("select count(*) from information_schema.tables "
                        "where table_schema in ('main','_truth')").fetchone()[0]
        print(f"    DuckDB DDL executed cleanly: {n} tables created")
    except ImportError:
        print("    (duckdb not installed here: DDL not executed. Run `pip install duckdb` and re-run.)")
